-- ============================================================
-- Component benchmark tests and immutable observations
-- 작성일: 2026-09-10
--
-- 이 migration은 기존 게임 FPS/추천 조합 테이블과 분리된 additive schema다.
-- 점수는 표준 부품(PART_ID)을 기준으로 비교하고, 출처 원본/SKU/조건을 보존한다.
-- ============================================================

CREATE TABLE IF NOT EXISTS `benchmark_component_tests` (
  `BENCHMARK_COMPONENT_TEST_ID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `BENCHMARK_CODE` VARCHAR(40) NOT NULL,
  `TEST_NAME` VARCHAR(120) NOT NULL,
  `TEST_VERSION` VARCHAR(80) NOT NULL,
  `SCORE_METRIC` VARCHAR(60) NOT NULL,
  `DEVICE_TYPE` VARCHAR(10) NOT NULL,
  `SCORE_UNIT` VARCHAR(30) NOT NULL,
  `COMPARABLE_GROUP_KEY` VARCHAR(180) NOT NULL,
  `IS_ACTIVE` CHAR(1) NOT NULL DEFAULT 'Y',
  `CREATED_DT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_DT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`BENCHMARK_COMPONENT_TEST_ID`),
  UNIQUE KEY `uk_benchmark_component_test` (`BENCHMARK_CODE`, `TEST_VERSION`, `SCORE_METRIC`, `DEVICE_TYPE`),
  UNIQUE KEY `uk_benchmark_component_group` (`COMPARABLE_GROUP_KEY`),
  KEY `idx_benchmark_component_test_device` (`DEVICE_TYPE`, `IS_ACTIVE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `benchmark_component_observations` (
  `BENCHMARK_COMPONENT_OBSERVATION_ID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `BENCHMARK_COMPONENT_TEST_ID` BIGINT UNSIGNED NOT NULL,
  `BENCHMARK_SOURCE_ID` BIGINT NOT NULL,
  `PART_ID` BIGINT UNSIGNED NULL,
  `SUPPLIER_PRODUCT_ID` BIGINT UNSIGNED NULL,
  `EXTERNAL_RESULT_ID` VARCHAR(180) NOT NULL,
  `RAW_COMPONENT_NAME` VARCHAR(255) NOT NULL,
  `NORMALIZED_MODEL_KEY` VARCHAR(220) NULL,
  `SCORE` DECIMAL(14,4) NOT NULL,
  `EVIDENCE_TYPE` VARCHAR(30) NOT NULL,
  `SOURCE_URL` VARCHAR(1000) NOT NULL,
  `TEST_SYSTEM_JSON` JSON NULL,
  `DRIVER_VERSION` VARCHAR(120) NULL,
  `OS_VERSION` VARCHAR(120) NULL,
  `OVERCLOCK_STATUS` VARCHAR(40) NULL,
  `RAW_JSON` JSON NULL,
  `CAPTURED_DT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `CREATED_DT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_DT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`BENCHMARK_COMPONENT_OBSERVATION_ID`),
  UNIQUE KEY `uk_benchmark_component_observation_source_result`
    (`BENCHMARK_SOURCE_ID`, `BENCHMARK_COMPONENT_TEST_ID`, `EXTERNAL_RESULT_ID`),
  KEY `idx_benchmark_component_observation_part_test`
    (`PART_ID`, `BENCHMARK_COMPONENT_TEST_ID`, `EVIDENCE_TYPE`),
  KEY `idx_benchmark_component_observation_model_test`
    (`NORMALIZED_MODEL_KEY`, `BENCHMARK_COMPONENT_TEST_ID`),
  CONSTRAINT `fk_benchmark_component_observation_test`
    FOREIGN KEY (`BENCHMARK_COMPONENT_TEST_ID`) REFERENCES `benchmark_component_tests` (`BENCHMARK_COMPONENT_TEST_ID`)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_benchmark_component_observation_source`
    FOREIGN KEY (`BENCHMARK_SOURCE_ID`) REFERENCES `benchmark_sources` (`BENCHMARK_SOURCE_ID`)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_benchmark_component_observation_part`
    FOREIGN KEY (`PART_ID`) REFERENCES `parts` (`PART_ID`)
    ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_benchmark_component_observation_product`
    FOREIGN KEY (`SUPPLIER_PRODUCT_ID`) REFERENCES `supplier_products` (`SUPPLIER_PRODUCT_ID`)
    ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
